@dataclass
class Report:
    lines: list = field(default_factory=list)
    write: object = None

    def add(self, status, name, detail=""):
        self.lines.append((status, name, detail))
        if self.write is not None:
            self.write(f"[{status}] {name}" + (f" - {detail}" if detail else ""))

    def ok(self, name, detail=""):
        self.add("PASS", name, detail)

    def fail(self, name, detail=""):
        self.add("FAIL", name, detail)

    def info(self, name, detail=""):
        self.add("INFO", name, detail)

    def warn(self, name, detail=""):
        self.add("WARN", name, detail)

    def check(self, condition, name, detail=""):
        (self.ok if condition else self.fail)(name, detail)
        return bool(condition)

    @property
    def passed(self):
        return any(status == "PASS" for status, _n, _d in self.lines) and not any(
            status == "FAIL" for status, _n, _d in self.lines
        )


