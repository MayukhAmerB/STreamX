class SimulatedOwncast:
    """Owncast's HLS output on 127.0.0.1: a master playlist with two variants
    (the filter must pick ``0``, the larger one), a live media playlist that
    grows every 2 s with a sliding window, the offline tail, and reconnects
    with fresh segment names."""

    def __init__(self, directory, phases, offline_name, window=4, segment_seconds=SEGMENT_SECONDS,
                 offline_seconds=OFFLINE_SECONDS):
        self.segment_seconds = float(segment_seconds)
        self.offline_seconds = float(offline_seconds)
        self.directory = Path(directory)
        self.phases = phases  # name -> [(segment file, duration)]
        self.offline_name = offline_name
        self.window = window
        self._lock = threading.Lock()
        self._phase = None
        self._offline = False
        self._started = 0.0
        self.requests = []  # (path, status)
        self.completed = set()  # segment file names fully served
        self._server = None

    # state changes (driver thread)
    def go_live(self, phase):
        with self._lock:
            self._phase, self._offline, self._started = phase, False, time.monotonic()

    def go_offline(self):
        with self._lock:
            self._offline = True

    def published(self, phase):
        with self._lock:
            if self._phase != phase:
                return 0
            if self._offline:
                return len(self.phases[phase])
            elapsed = time.monotonic() - self._started
            return min(len(self.phases[phase]), 1 + int(elapsed // self.segment_seconds))

    def was_requested(self, fragment):
        with self._lock:
            return any(fragment in path for path, _status in self.requests)

    # HTTP
    def media_playlist(self):
        with self._lock:
            phase, offline = self._phase, self._offline
        if phase is None:
            return None
        segments = self.phases[phase]
        available = self.published(phase)
        start = max(0, available - self.window)
        longest = max(duration for _name, duration in segments)
        target = max(1, int(max(longest, self.offline_seconds if offline else 0) + 0.999))
        lines = ["#EXTM3U", "#EXT-X-VERSION:3", f"#EXT-X-TARGETDURATION:{target}", f"#EXT-X-MEDIA-SEQUENCE:{start}"]
        for name, duration in segments[start:available]:
            lines += [f"#EXTINF:{duration:.6f},", name]
        if offline:
            lines += ["#EXT-X-DISCONTINUITY", f"#EXTINF:{self.offline_seconds:.6f},", self.offline_name, "#EXT-X-ENDLIST"]
        return "\n".join(lines) + "\n"

    @staticmethod
    def master_playlist():
        return (
            "#EXTM3U\n#EXT-X-VERSION:3\n"
            "#EXT-X-STREAM-INF:BANDWIDTH=300000,RESOLUTION=256x144,CODECS=\"avc1.42c015,mp4a.40.2\"\n1/stream.m3u8\n"
            f"#EXT-X-STREAM-INF:BANDWIDTH=900000,RESOLUTION={FRAME},CODECS=\"avc1.42c01e,mp4a.40.2\"\n0/stream.m3u8\n"
        )

    def start(self):
        simulator = self

        class Handler(BaseHTTPRequestHandler):
            protocol_version = "HTTP/1.1"

            def log_message(self, *args):
                pass

            def _send(self, status, body, content_type):
                with simulator._lock:
                    simulator.requests.append((self.path, status))
                self.send_response(status)
                self.send_header("Content-Type", content_type)
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

            def do_GET(self):  # noqa: N802
                path = self.path.split("?", 1)[0]
                if path == "/hls/stream.m3u8":
                    self._send(200, simulator.master_playlist().encode(), "application/vnd.apple.mpegurl")
                    return
                parts = path.strip("/").split("/")
                if len(parts) == 3 and parts[0] == "hls" and parts[1] in {"0", "1"}:
                    name = parts[2]
                    if name == "stream.m3u8":
                        text = simulator.media_playlist()
                        if text is None:
                            self._send(404, b"offline", "text/plain")
                        else:
                            self._send(200, text.encode(), "application/vnd.apple.mpegurl")
                        return
                    candidate = simulator.directory / name
                    if "/" not in name and ".." not in name and candidate.is_file():
                        self._send(200, candidate.read_bytes(), "video/mp2t")
                        with simulator._lock:
                            simulator.completed.add(name)
                        return
                self._send(404, b"not found", "text/plain")

        self._server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self._server.daemon_threads = True
        threading.Thread(target=self._server.serve_forever, kwargs={"poll_interval": 0.2}, daemon=True).start()
        host, port = self._server.server_address[:2]
        return f"http://{host}:{port}/hls/stream.m3u8"

    def stop(self):
        if self._server is not None:
            self._server.shutdown()
            self._server.server_close()
            self._server = None


