def _binary(name, default):
    return str(getattr(settings, name, default) or default)


def _run(cmd, timeout=180):
    from . import ffmpeg as recording_ffmpeg

    result = subprocess.run(
        recording_ffmpeg._niced(cmd), capture_output=True, text=True, timeout=timeout, check=False
    )
    if result.returncode != 0:
        raise VerificationError(f"{Path(cmd[0]).name} failed ({result.returncode}): {(result.stderr or '')[-1500:]}")
    return result


def probe(path):
    """ffprobe summary: {"duration", "start", "streams": [(type, codec, duration)]}."""
    result = _run(
        [
            _binary("FFPROBE_BINARY", "ffprobe"),
            "-v",
            "error",
            "-show_entries",
            "format=duration,start_time:stream=codec_type,codec_name,duration",
            "-of",
            "json",
            str(path),
        ],
        timeout=60,
    )
    data = json.loads(result.stdout or "{}")
    fmt = data.get("format") or {}

    def number(value):
        try:
            return float(value)
        except (TypeError, ValueError):
            return None

    streams = [
        (item.get("codec_type"), item.get("codec_name"), number(item.get("duration")))
        for item in data.get("streams") or []
    ]
    return {"duration": number(fmt.get("duration")), "start": number(fmt.get("start_time")), "streams": streams}


def mp4_top_level_boxes(path, limit=64):
    boxes = []
    size = os.path.getsize(path)
    with open(path, "rb") as handle:
        offset = 0
        while offset + 8 <= size and len(boxes) < limit:
            handle.seek(offset)
            header = handle.read(8)
            box_size = int.from_bytes(header[:4], "big")
            box_type = header[4:8].decode("latin-1")
            if box_size == 1:
                box_size = int.from_bytes(handle.read(8), "big")
            elif box_size == 0:
                box_size = size - offset
            boxes.append(box_type)
            if box_size < 8:
                break
            offset += box_size
    return boxes


def is_faststart(path):
    boxes = mp4_top_level_boxes(path)
    return "moov" in boxes and "mdat" in boxes and boxes.index("moov") < boxes.index("mdat")


def _lavfi_av(seconds, *, video, tone):
    return [
        "-f",
        "lavfi",
        "-i",
        f"{video}=size={FRAME}:rate={FPS}:duration={seconds}",
        "-f",
        "lavfi",
        "-i",
        f"sine=frequency={tone}:sample_rate=48000:duration={seconds}",
        "-map",
        "0:v",
        "-map",
        "1:a",
        "-c:v",
        "libx264",
        "-preset",
        "ultrafast",
        "-pix_fmt",
        "yuv420p",
        "-g",
        str(FPS * SEGMENT_SECONDS),
        "-keyint_min",
        str(FPS * SEGMENT_SECONDS),
        "-sc_threshold",
        "0",
        "-c:a",
        "aac",
        "-b:a",
        "64k",
        "-t",
        str(seconds),
    ]


def generate_hls(directory, prefix, seconds, *, video, tone):
    directory.mkdir(parents=True, exist_ok=True)
    playlist = directory / f"{prefix}.m3u8"
    _run(
        [_binary("FFMPEG_BINARY", "ffmpeg"), "-hide_banner", "-nostdin", "-loglevel", "error", "-y"]
        + _lavfi_av(seconds, video=video, tone=tone)
        + [
            "-f",
            "hls",
            "-hls_time",
            str(SEGMENT_SECONDS),
            "-hls_list_size",
            "0",
            "-hls_segment_filename",
            str(directory / f"seg-{prefix}-%03d.ts"),
            str(playlist),
        ]
    )
    segments, duration = [], None
    for line in playlist.read_text(encoding="utf-8").splitlines():
        if line.startswith("#EXTINF:"):
            duration = float(line.split(":", 1)[1].split(",", 1)[0])
        elif line and not line.startswith("#"):
            segments.append((line.strip(), duration or float(SEGMENT_SECONDS)))
    if not segments:
        raise VerificationError(f"ffmpeg produced no HLS segments for {prefix}")
    return segments


def generate_file(path, seconds, *, video, tone, container):
    path.parent.mkdir(parents=True, exist_ok=True)
    _run(
        [_binary("FFMPEG_BINARY", "ffmpeg"), "-hide_banner", "-nostdin", "-loglevel", "error", "-y"]
        + _lavfi_av(seconds, video=video, tone=tone)
        + ["-f", container, str(path)]
    )
    return path


