    try:
        # (a) live
        feed.go_live("a")
        last_a = feed.phases["a"][-1][0]
        live_ok = _drive(recorder, lambda: last_a in feed.completed, timeout=LIVE_A_SEGMENTS * SEGMENT_SECONDS + 40)
        if not report.check(live_ok, "(a) live: every live segment captured",
                            f"{len(feed.completed)} segment(s) read. {_part_logs(work_dir)}"):
            return
        time.sleep(1.0)
        # (b) OBS disconnects: Owncast appends its offline clip and ENDLIST
        feed.go_offline()
        status.update(online=False)
        offline_started = time.monotonic()
        exited = _drive(recorder, lambda: recording.pk not in recorder.captures, timeout=60)
        waited = time.monotonic() - offline_started
        report.check(exited and waited < 20, "(b) offline tail: ffmpeg ended the part by itself",
                     f"after {waited:.1f}s (the filter closes the playlist; >20s would mean it hung until "
                     "-m3u8_hold_counters)")
        report.check(not feed.was_requested("offline-v2.ts"), "(b) offline clip was never downloaded")
        # (c) OBS reconnects: fresh playlist, fresh segment names
        feed.go_live("b")
        status.update(online=True, lastConnectTime="2026-01-01T10:05:00Z")
        last_b = feed.phases["b"][-1][0]
        reconnect_ok = _drive(recorder, lambda: last_b in feed.completed,
                              timeout=LIVE_B_SEGMENTS * SEGMENT_SECONDS + 40)
        report.check(reconnect_ok, "(c) reconnect: new connection captured", _part_logs(work_dir))
        _drive(recorder, lambda: False, timeout=1.5)
        # (d) the class ends -> the recorder stops ffmpeg and finalizes
        RealtimeSession.objects.filter(pk=session.pk).update(
            status=RealtimeSession.STATUS_ENDED, ended_at=timezone.now()
        )
        recorder.capture_active()
        recording.refresh_from_db()
        report.check(recording.state == R.STATE_FINALIZING and not recorder.captures,
                     "(d) stop: capture stopped, recording finalizing", recording.state)
        parts = list_parts(work_dir)
        report.check(len(parts) == 2, "two parts (one per OBS connection)", ", ".join(p.name for p in parts))
        expected_a = sum(duration for _n, duration in feed.phases["a"])
        expected_b = sum(duration for _n, duration in feed.phases["b"])
        for part, expected in zip(parts, (expected_a, expected_b)):
            seconds = probe(part)["duration"] or 0.0
            report.check(abs(seconds - expected) <= DURATION_TOLERANCE, f"{part.name}: live content only",
                         f"{seconds:.2f}s, expected {expected:.1f}s (the offline clip is {OFFLINE_SECONDS}s)")
        report.check(not feed.was_requested("/hls/1/"), "only the best variant was read",
                     "variant 1 (256x144) never requested")

        recorder.finalize_recording(recording.pk)
        recording.refresh_from_db()
        if not report.check(recording.state == R.STATE_PROCESSING and recording.lecture_id,
                            "finalize: concat -> MP4 -> lecture", f"{recording.state} {recording.error}"):
            return
        lecture = Lecture.objects.get(pk=recording.lecture_id)
        video = media_root / lecture.video_file.name
        report.check(video.is_file(), "final MP4 in the module folder", lecture.video_file.name)
        report.check(lecture.video_file.name.startswith(f"lecture_videos/") and f"/module_{module.pk}/"
                     in lecture.video_file.name, "MP4 path is lecture_videos/<course>/module_<id>/")
        _check_mp4(report, "final MP4", video, expected_seconds=expected_a + expected_b)
        report.check(lecture.section_id == module.pk and not lecture.is_published,
                     "lecture created unpublished in the right module", lecture.title)
        report.check(lecture.description == MODULE_DESCRIPTION, "lecture has the module description")
        report.check(recording.duration_seconds and abs(recording.duration_seconds - (expected_a + expected_b)) <= 3,
                     "recording duration recorded", f"{recording.duration_seconds}s")
        report.check(not work_dir.exists(), "captured parts removed after a successful finalize")

        # Host Studio: a LiveKit egress MP4 through the same concat path
        egress_recording = R.objects.create(
            session=session, module=module, source=R.SOURCE_LIVEKIT_EGRESS, state=R.STATE_FINALIZING,
            source_path=str(egress), started_at=timezone.now(), stop_requested_at=timezone.now(),
        )
        recorder.finalize_recording(egress_recording.pk)
        egress_recording.refresh_from_db()
        if report.check(egress_recording.state == R.STATE_PROCESSING, "Host Studio egress file -> lecture",
                        egress_recording.error):
            egress_video = media_root / egress_recording.lecture.video_file.name
            _check_mp4(report, "egress MP4", egress_video, expected_seconds=EGRESS_SECONDS)
            report.check(egress.is_file(), "the LiveKit original is left in place")

        # OBS MKV upload -> remux -> swapped into the first lecture
        staged_name = f"class-recording-uploads/obs-verify-{token}.mkv"
        (media_root / "class-recording-uploads").mkdir(parents=True, exist_ok=True)
        shutil.copyfile(mkv, media_root / staged_name)
        upload = R.objects.create(
            session=session, module=module, lecture=lecture, source=R.SOURCE_OBS_UPLOAD, state=R.STATE_FINALIZING,
            source_path=staged_name, started_at=timezone.now(), stop_requested_at=timezone.now(),
        )
        recorder.finalize_recording(upload.pk)
        upload.refresh_from_db()
        lecture.refresh_from_db()
        if report.check(upload.state == R.STATE_PROCESSING, "OBS MKV upload remuxed and swapped in", upload.error):
            report.check(lecture.video_file.name.endswith(".mp4"), "lecture now uses the remuxed MP4",
                         lecture.video_file.name)
            _check_mp4(report, "remuxed OBS MP4", media_root / lecture.video_file.name, expected_seconds=MKV_SECONDS)

        # Already-made recordings: scan -> imported -> publish to module
        scan = importer.scan_existing_recordings(min_age_seconds=3600)
        imported = list(R.objects.filter(source=R.SOURCE_IMPORTED, source_path=str(old_import)))
        report.check(len(imported) == 1 and len(scan.created) == 1, "scan lists the old file as imported",
                     scan.summary())
        if imported:
            row = imported[0]
            report.check(row.state == R.STATE_IMPORTED and abs((row.duration_seconds or 0) - IMPORT_SECONDS) <= 1,
                         "imported row: unassigned, with ffprobe duration", f"{row.state} {row.duration_seconds}s")
            again = importer.scan_existing_recordings(min_age_seconds=3600)
            report.check(not again.created and R.objects.filter(source=R.SOURCE_IMPORTED).count() == 1,
                         "re-scan is idempotent", again.summary())
            services.publish_to_module(row, module)
            recorder.finalize_recording(row.pk)
            row.refresh_from_db()
            if report.check(row.state == R.STATE_PROCESSING and row.lecture_id, "publish to module -> lecture",
                            row.error):
                imported_lecture = Lecture.objects.get(pk=row.lecture_id)
                report.check(
                    imported_lecture.section_id == module.pk and not imported_lecture.is_published
                    and imported_lecture.description == MODULE_DESCRIPTION,
                    "imported lecture unpublished in the module with its description", imported_lecture.title,
                )
                # Imported MP4s are linked/copied as they are (the HLS stream is built from them).
                _check_mp4(report, "imported MP4", media_root / imported_lecture.video_file.name,
                           expected_seconds=IMPORT_SECONDS, faststart=False)
                report.check(old_import.is_file(), "the imported original is left in place")
    finally:
        recorder.shutdown()
