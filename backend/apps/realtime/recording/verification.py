"""End-to-end check of the class-recording pipeline with the real ffmpeg.

Used by ``manage.py verify_recording_pipeline`` (and by a test that only runs
where ffmpeg is installed). It proves, on the machine it runs on, that:

1. a live HLS feed (generated by ffmpeg itself: testsrc + sine, H.264/AAC,
   2 s segments) served like Owncast serves it is captured by the recorder's
   real capture code (``StreamRecorder.capture_active`` -> ffmpeg -> playlist
   filter), including
   a. live segments arriving every 2 s,
   b. Owncast's offline tail (``#EXT-X-DISCONTINUITY`` + ``offline-v2.ts`` +
      ``#EXT-X-ENDLIST``) when OBS disconnects -- the offline clip must never
      be downloaded and ffmpeg must end the part by itself,
   c. a reconnect with fresh segment names -> a second part,
   d. the class being ended -> finalize;
2. the real finalize (concat of the parts into a faststart MP4) produces a
   valid H.264 + AAC MP4 of the live duration, and an unpublished lecture in
   the right module with the module's description;
3. a Host Studio (LiveKit egress) MP4, an OBS MKV upload (remux) and an
   imported file (scan + "publish to module") go through their real
   finalize paths too.

Only Owncast's status API is replaced (by the simulated feed's state).

Safe on production, inside the running stream-recorder container:
* every database row (course, module, session, recordings, lectures) is
  created inside one transaction that is always rolled back -- other
  processes never see them (the live recorder and the transcoder only see
  committed rows) and nothing is left behind;
* MEDIA_ROOT, the recorder work dir and the LiveKit output root are pointed at
  a fresh temporary directory for the duration of the run (this process
  only), which is deleted afterwards;
* the simulated Owncast and the playlist filter listen on 127.0.0.1 on
  ephemeral ports; the recorder used here is limited to its own recording id
  and never touches the Redis leader key, real sessions or the live capture;
* the course-list cache version is not bumped (that would be the only write
  outside the transaction).
"""

