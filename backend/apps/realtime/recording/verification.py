def _preflight(report):
    ffmpeg_bin = shutil.which(_binary("FFMPEG_BINARY", "ffmpeg"))
    ffprobe_bin = shutil.which(_binary("FFPROBE_BINARY", "ffprobe"))
    if not report.check(ffmpeg_bin and ffprobe_bin, "ffmpeg and ffprobe installed", f"{ffmpeg_bin} / {ffprobe_bin}"):
        return False
    version = _run([ffmpeg_bin, "-hide_banner", "-version"], timeout=30).stdout.splitlines()[0]
    report.info("ffmpeg version", version)
    encoders = _run([ffmpeg_bin, "-hide_banner", "-encoders"], timeout=30).stdout
    demuxers = _run([ffmpeg_bin, "-hide_banner", "-demuxers"], timeout=30).stdout
    muxers = _run([ffmpeg_bin, "-hide_banner", "-muxers"], timeout=30).stdout

    def has(text, name):
        return any(len(line.split()) > 1 and name in line.split()[1].split(",") for line in text.splitlines())

    missing = [f"encoder {name}" for name in ("libx264", "aac") if not has(encoders, name)]
    missing += [f"demuxer {name}" for name in ("hls", "concat", "matroska", "mpegts") if not has(demuxers, name)]
    missing += [f"muxer {name}" for name in ("mpegts", "mp4", "matroska", "hls") if not has(muxers, name)]
    return report.check(not missing, "ffmpeg has the codecs and formats used", ", ".join(missing) or "all present")


def _environment(report):
    """Informational: the real folders the service uses (never written to)."""
    from . import config
    from .publisher import free_disk_bytes

    reserve = config.min_free_bytes()
    for label, raw in (
        ("MEDIA_ROOT", settings.MEDIA_ROOT),
        ("recorder work dir", config.work_root()),
        ("LiveKit output root", getattr(settings, "LIVEKIT_RECORDING_LOCAL_OUTPUT_ROOT", "")),
    ):
        path = Path(str(raw or ""))
        probe_dir = path
        while not probe_dir.exists() and probe_dir.parent != probe_dir:
            probe_dir = probe_dir.parent
        writable = os.access(probe_dir, os.W_OK)
        free = free_disk_bytes(path)
        detail = f"{path} (exists={path.exists()}, writable={writable}, free={_gib(free)})"
        if free is not None and free < reserve:
            report.warn(f"{label} free space below STREAM_RECORDER_MIN_FREE_BYTES ({_gib(reserve)})", detail)
        else:
            report.info(label, detail)


def _gib(value):
    return "unknown" if value is None else f"{value / (1024 ** 3):.1f} GiB"


def _refuse_collisions():
    from apps.courses.models import Course, Section

    from ..models import RealtimeSession

    clashes = []
    if Course.objects.filter(title__startswith=MARKER).exists():
        clashes.append("course")
    if Section.objects.filter(title__startswith=MARKER).exists():
        clashes.append("module")
    if RealtimeSession.objects.filter(title__startswith=MARKER).exists():
        clashes.append("session")
    if clashes:
        raise VerificationError(
            f"Rows titled '{MARKER}...' already exist ({', '.join(clashes)}); refusing to run. They are not from "
            "this check (its rows are always rolled back) -- investigate before re-running."
        )


def _drive(recorder, until, *, timeout, step=0.25):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        recorder.capture_active()
        if until():
            return True
        time.sleep(step)
    recorder.capture_active()
    return until()


def _part_logs(work_dir):
    lines = []
    for log in sorted(Path(work_dir).glob("part-*.log")):
        text = log.read_text(encoding="utf-8", errors="replace").strip()
        if text:
            lines.append(f"{log.name}: {text[-600:]}")
    return " | ".join(lines)


def _check_mp4(report, label, path, *, expected_seconds, faststart=True):
    info = probe(path)
    kinds = {(kind, codec) for kind, codec, _duration in info["streams"]}
    report.check(("video", "h264") in kinds and ("audio", "aac") in kinds, f"{label}: H.264 video + AAC audio",
                 str(sorted(kinds)))
    duration = info["duration"] or 0.0
    report.check(
        abs(duration - expected_seconds) <= DURATION_TOLERANCE,
        f"{label}: duration matches",
        f"{duration:.2f}s, expected {expected_seconds:.1f}s +/- {DURATION_TOLERANCE:.0f}s",
    )
    durations = {kind: value for kind, _codec, value in info["streams"] if value}
    if "video" in durations and "audio" in durations:
        drift = abs(durations["video"] - durations["audio"])
        report.check(drift <= 1.0, f"{label}: audio and video stay together", f"video {durations['video']:.2f}s, "
                     f"audio {durations['audio']:.2f}s")
    if faststart:
        report.check(is_faststart(path), f"{label}: faststart (moov before mdat)",
                     " ".join(mp4_top_level_boxes(path)[:6]))
    return info


def run_verification(*, keep_temp=False, write=None):
    """Run every check; returns a Report (``report.passed``)."""
    report = Report(write=write)
    try:
        if not _preflight(report):
            return report
        _environment(report)
        _refuse_collisions()
    except VerificationError as exc:
        report.fail("preflight", str(exc))
        return report

    base = Path(tempfile.mkdtemp(prefix="verify-recording-pipeline-"))
    # Spaces and an apostrophe on purpose: the concat list escaping is exercised for real.
    media_root = base / "media it's"
    work_root = base / "work dir's"
    livekit_root = base / "livekit out"
    source_dir = base / "source"
    for directory in (media_root, work_root, livekit_root, source_dir):
        directory.mkdir(parents=True)
    report.info("temporary workspace", str(base))
    feed = None
    try:
        started = time.monotonic()
        phases = {
            "a": generate_hls(source_dir, "a", LIVE_A_SEGMENTS * SEGMENT_SECONDS, video="testsrc", tone=440),
            "b": generate_hls(source_dir, "b", LIVE_B_SEGMENTS * SEGMENT_SECONDS, video="testsrc2", tone=660),
        }
        generate_file(source_dir / "offline-v2.ts", OFFLINE_SECONDS, video="smptebars", tone=1000, container="mpegts")
        mkv = generate_file(source_dir / "obs-recording.mkv", MKV_SECONDS, video="testsrc2", tone=550,
                            container="matroska")
        egress = generate_file(livekit_root / "room-egress.mp4", EGRESS_SECONDS, video="testsrc", tone=330,
                               container="mp4")
        old_import = generate_file(livekit_root / "old-class" / "2026-01-15 10-00-00.mp4", IMPORT_SECONDS,
                                   video="testsrc", tone=770, container="mp4")
        day_ago = time.time() - 86400
        os.utime(old_import, (day_ago, day_ago))
        report.ok("test media generated with ffmpeg", f"{time.monotonic() - started:.1f}s")
        feed = SimulatedOwncast(source_dir, phases, "offline-v2.ts")
        source_url = feed.start()
        report.info("simulated Owncast", source_url)

        overrides = override_settings(
            MEDIA_ROOT=str(media_root),
            STREAM_RECORDER_ENABLED=True,
            STREAM_RECORDER_SOURCE_URL=source_url,
            STREAM_RECORDER_WORK_DIR=str(work_root),
            LIVEKIT_RECORDING_LOCAL_OUTPUT_ROOT=str(livekit_root),
            LIVEKIT_RECORDING_FILEPATH_PREFIX="/recordings",
            STREAM_RECORDER_MIN_FREE_BYTES=0,
            STREAM_RECORDER_FILE_SETTLE_SECONDS=0,
            STREAM_RECORDER_RESTART_BACKOFF_SECONDS=2,
            STREAM_RECORDER_HEARTBEAT_SECONDS=1,
            STREAM_RECORDER_HLS_FILTER=True,
        )
        with ExitStack() as stack:
            stack.enter_context(overrides)
            # The only write outside the transaction would be this cache bump.
            stack.enter_context(mock.patch("apps.courses.signals.bump_course_list_cache_version"))
            stack.enter_context(mock.patch("apps.realtime.recording.publisher.bump_course_list_cache_version"))
            stack.enter_context(mock.patch("apps.realtime.recording.services.bump_course_list_cache_version"))
            try:
                with transaction.atomic():
                    _scenario(report, feed, media_root=media_root, work_root=work_root, mkv=mkv, egress=egress,
                              old_import=old_import)
                    raise _Rollback()
            except _Rollback:
                pass
            except VerificationError as exc:  # rolled back as well
                report.fail("pipeline", str(exc))
            except Exception as exc:  # rolled back as well; report, never crash the shell
                report.fail("pipeline crashed", f"{type(exc).__name__}: {exc}")
            _check_no_trace(report)
    except VerificationError as exc:
        report.fail("pipeline", str(exc))
    except Exception as exc:  # report, never crash the container's shell
        report.fail("pipeline crashed", f"{type(exc).__name__}: {exc}")
    finally:
        if feed is not None:
            feed.stop()
        if keep_temp:
            report.info("temporary files kept", str(base))
        else:
            shutil.rmtree(base, ignore_errors=True)
    return report


def _check_no_trace(report):
    from apps.courses.models import Course, Lecture, Section

    from ..models import RealtimeSession
    from .models import ClassRecording

    leftovers = (
        Course.objects.filter(title__startswith=MARKER).count()
        + Section.objects.filter(title__startswith=MARKER).count()
        + RealtimeSession.objects.filter(title__startswith=MARKER).count()
        + Lecture.objects.filter(section__title__startswith=MARKER).count()
        + ClassRecording.objects.filter(session__title__startswith=MARKER).count()
    )
    report.check(leftovers == 0, "database left unchanged (transaction rolled back)", f"{leftovers} leftover row(s)")


